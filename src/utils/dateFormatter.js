/**
 * Utility functions for formatting LocalDateTime ISO strings from Spring Boot
 */

/**
 * Formats an ISO string (e.g. "2026-11-05T10:30:00") into "Nov 5, 2026, 10:30 AM"
 */
export function formatDateTime(isoString) {
  if (!isoString) return 'N/A';
  try {
    const date = new Date(isoString);
    if (isNaN(date.getTime())) return isoString;
    return new Intl.DateTimeFormat('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
      hour: 'numeric',
      minute: '2-digit',
      hour12: true,
    }).format(date);
  } catch {
    return isoString;
  }
}

